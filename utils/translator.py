import os
import threading

try:
    # Prefer Google Cloud Translate when credentials available
    from google.cloud import translate_v2 as gc_translate
    _GC_AVAILABLE = True
except Exception:
    _GC_AVAILABLE = False

_FALLBACK = False
try:
    from googletrans import Translator as GTTranslator
    _FALLBACK = True
except Exception:
    _FALLBACK = False


# ----------------------------------------------------------------------
# FAST TRANSLATION CORE
# ----------------------------------------------------------------------
# The original code created a new Translator() instance and made one network
# call per text field. A full multi-agent report has ~60-80 text fields, so
# that meant 60-80 sequential network round-trips — the main cause of the
# "Translating AI second opinion..." hang.
#
# This rework uses three strategies:
#   1. Reuse a single Translator() instance (creating it once is expensive).
#   2. Cache results per (source_text, lang) so repeated strings (e.g. the
#      med disclaimer used in 3 places) are translated only once.
#   3. Provide a batch API that translates ALL unique strings in ONE network
#      call, which is dramatically faster than N calls.

_TRANSLATION_CACHE = {}
_CACHE_LOCK = threading.Lock()
_GT_INSTANCE = None
_GT_INSTANCE_LOCK = threading.Lock()


def _get_gt():
    """Return a lazily-created, reused googletrans Translator instance."""
    global _GT_INSTANCE
    if _GT_INSTANCE is None:
        with _GT_INSTANCE_LOCK:
            if _GT_INSTANCE is None:
                _GT_INSTANCE = GTTranslator()
    return _GT_INSTANCE


def _cache_get(text, lang):
    with _CACHE_LOCK:
        return _TRANSLATION_CACHE.get((text, lang))


def _cache_set(text, lang, value):
    # Keep the cache bounded to avoid unbounded growth on long-running servers.
    if len(_TRANSLATION_CACHE) > 4000:
        with _CACHE_LOCK:
            if len(_TRANSLATION_CACHE) > 4000:
                # Drop a random-ish subset (simplest bounded eviction).
                keys = list(_TRANSLATION_CACHE.keys())
                for k in keys[: len(keys) // 2]:
                    _TRANSLATION_CACHE.pop(k, None)
    with _CACHE_LOCK:
        _TRANSLATION_CACHE[(text, lang)] = value


def translate_text_batch(texts, target_lang="en"):
    """Translate a LIST of strings to `target_lang` in a single batched call.

    Returns a list of translated strings aligned with the input order. Strings
    that are already cached are not re-translated. Any failure falls back to
    the original text so the report always stays readable.

    This is the fast path used by the multi-agent translator. It reduces the
    number of network round-trips from N to 1.
    """
    if not texts:
        return texts
    if target_lang in (None, "", "en"):
        return list(texts)

    # Drop empty/duplicate strings; keep index mapping.
    unique = []
    index_map = []  # (original_index, unique_index)
    for i, t in enumerate(texts):
        s = str(t) if t is not None else ""
        if not s:
            index_map.append((i, None))
            unique.append("")
            continue
        cached = _cache_get(s, target_lang)
        if cached is not None:
            index_map.append((i, cached))
            unique.append("")
        else:
            index_map.append((i, None))
            unique.append(s)

    # Collect the strings that actually need network translation.
    to_translate = [u for u in unique if u]
    results = _batch_translate(to_translate, target_lang)

    # Build the final output in input order.
    out = []
    res_iter = iter(results)
    for i, u in enumerate(unique):
        mapped = index_map[i][1]
        if isinstance(mapped, str):
            out.append(mapped)
        elif u:
            val = next(res_iter, u)
            _cache_set(u, target_lang, val)
            out.append(val)
        else:
            out.append("")
    return out


def _is_same_as_input(translated, original):
    """Return True when the 'translated' output is effectively identical to the
    input (i.e. the batch call silently returned the originals unchanged)."""
    if translated is None:
        return True
    if isinstance(translated, str):
        return translated.strip() == str(original).strip()
    return False


def _batch_translate(texts, target_lang):
    """Perform the actual network translation for a list of non-empty strings.

    NOTE: googletrans 4.0.0-rc1 has a known bug where passing a LIST to
    translate() sometimes returns the input strings unchanged (no translation).
    We detect that situation and fall back to translating each string via the
    reliable single-string path, which is still cached so repeat calls are fast.
    """
    if not texts:
        return []

    # Try Google Cloud Translate first (batched API).
    if _GC_AVAILABLE and os.environ.get('GOOGLE_APPLICATION_CREDENTIALS'):
        try:
            client = gc_translate.Client()
            res = client.translate(texts, target_language=target_lang)
            if isinstance(res, list):
                out = [r.get('translatedText') or t for r, t in zip(res, texts)]
                # If any result is unchanged, trust only the true translations.
                if any(not _is_same_as_input(o, t) for o, t in zip(out, texts)):
                    return out
            return list(texts)
        except Exception:
            pass

    # Fallback to googletrans (no credentials required).
    if _FALLBACK:
        try:
            gt = _get_gt()
            out = gt.translate(texts, dest=target_lang)
            if isinstance(out, list):
                extracted = [o.text if hasattr(o, "text") else str(o) for o in out]
                # If the batch returned the originals unchanged (googletrans
                # list bug), fall through to per-string translation below.
                if any(not _is_same_as_input(o, t) for o, t in zip(extracted, texts)):
                    return extracted
        except Exception:
            pass

    # The batch call silently returned originals (googletrans list bug) or
    # failed. Fall back to translating each string individually via the
    # reliable single-string path, but run the network calls CONCURRENTLY with
    # a small thread pool so first-pass latency is N-waits instead of N×wait.
    # Results are cached inside translate_text, so repeat switches are instant.
    try:
        from concurrent.futures import ThreadPoolExecutor
        with ThreadPoolExecutor(max_workers=8) as ex:
            results = list(ex.map(lambda t: translate_text(t, target_lang=target_lang), texts))
        return list(results)
    except Exception:
        results = []
        for t in texts:
            try:
                results.append(translate_text(t, target_lang=target_lang))
            except Exception:
                results.append(t)
        return results


def translate_text(text, target_lang="en"):
    """Translate `text` to `target_lang`.

    Uses the shared translator instance and an in-memory cache so repeated
    strings are only translated once. Tries Google Cloud Translate (if
    installed and credentials configured), falls back to `googletrans` when
    available. If neither available or an error occurs, returns the original
    text.
    """
    if not text:
        return text

    if target_lang in (None, '', 'en'):
        return text

    s = str(text)
    cached = _cache_get(s, target_lang)
    if cached is not None:
        return cached

    # Try Google Cloud Translate first
    if _GC_AVAILABLE and os.environ.get('GOOGLE_APPLICATION_CREDENTIALS'):
        try:
            client = gc_translate.Client()
            res = client.translate(s, target_language=target_lang)
            out = res.get('translatedText') or s
            _cache_set(s, target_lang, out)
            return out
        except Exception:
            pass

    # Fallback to googletrans (no credentials required) — reuse the instance.
    if _FALLBACK:
        try:
            gt = _get_gt()
            out = gt.translate(s, dest=target_lang)
            out_text = out.text if hasattr(out, "text") else str(out)
            _cache_set(s, target_lang, out_text)
            return out_text
        except Exception:
            pass

    # Nothing worked — return original text
    return text
