def get_translation(lang_code="en"):
    """Returns the translation dictionary for the given language code (defaults to English).
    Merges the base report translations, the Multi-Agent AI Tumor Board labels, the
    Diagnostic Portal UI labels, and the Stage Guidance labels."""
    lang = (lang_code or "en").lower().strip()
    base = TRANSLATIONS.get(lang, TRANSLATIONS["en"])
    extra = MULTI_AGENT_TRANSLATIONS.get(lang, MULTI_AGENT_TRANSLATIONS["en"])
    portal = PORTAL_TRANSLATIONS.get(lang, PORTAL_TRANSLATIONS["en"])
    guidance = STAGE_GUIDANCE_TRANSLATIONS.get(lang, STAGE_GUIDANCE_TRANSLATIONS["en"])
    merged = dict(base)
    merged.update(extra)
    merged.update(portal)
    merged.update(guidance)
    return merged

