  /**
   * Recursive Lossless TextNode TreeWalker
   * Translates every visible text node across the entire DOM tree
   * without destroying or altering any HTML tags, icons, badges, or scripts.
   */
  function translateEntireDOM(targetLang) {
    const dict = TRANSLATIONS[targetLang] || {};

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        const parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        if (['SCRIPT', 'STYLE', 'CODE', 'PRE', 'NOSCRIPT'].includes(parent.tagName)) return NodeFilter.FILTER_REJECT;
        if (parent.closest('#globalLangSelector') || parent.closest('#langPickerMenu') || parent.classList.contains('no-translate')) {
          return NodeFilter.FILTER_REJECT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    });

    let node;
    while ((node = walker.nextNode())) {
      const raw = node.nodeValue;
      const trimmed = raw.trim();

      // Cache original English value on the node on first discovery
      if (node._origValue === undefined) {
        node._origValue = raw;
        node._origTrimmed = trimmed;
      }

      if (targetLang === 'en') {
        if (node._origValue !== undefined) {
          node.nodeValue = node._origValue;
        }
      } else {
        const lookupKey = node._origTrimmed;
        if (dict[lookupKey]) {
          // Replace only the trimmed portion to preserve original leading/trailing spaces
          node.nodeValue = node._origValue.replace(lookupKey, dict[lookupKey]);
        }
      }
    }

    // Translate placeholder attributes on inputs and textareas
    document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(el => {
      if (el._origPlaceholder === undefined) {
        el._origPlaceholder = el.getAttribute('placeholder');
      }
      if (targetLang === 'en') {
        el.setAttribute('placeholder', el._origPlaceholder);
      } else if (dict[el._origPlaceholder]) {
        el.setAttribute('placeholder', dict[el._origPlaceholder]);
      }
    });

    // Translate title attributes
    document.querySelectorAll('[title]').forEach(el => {
      if (el.id === 'globalLangSelector') return;
      if (el._origTitle === undefined) {
        el._origTitle = el.getAttribute('title');
      }
      if (targetLang === 'en') {
        el.setAttribute('title', el._origTitle);
      } else if (dict[el._origTitle]) {
        el.setAttribute('title', dict[el._origTitle]);
      }
    });
  }

  /**
   * Main Global Language Changer called by header dropdown or code
   */
  window.changeGlobalLanguage = function (lang) {
    if (!lang) lang = 'en';
    localStorage.setItem('mediscan_language', lang);

    // 1. Synchronize all language selectors on the page
    document.querySelectorAll('.lang-pill-select, #globalLangSelector, #langPickerSelect').forEach(sel => {
      if (sel && sel.value !== lang) sel.value = lang;
    });

    // 2. Synchronize hidden form fields
    const reportLangInput = document.getElementById('reportLanguageInput');
    if (reportLangInput) reportLangInput.value = lang;

    // 3. Set native typography & document direction (RTL for Arabic)
    if (FONT_MAP[lang]) {
      document.body.style.fontFamily = FONT_MAP[lang];
    } else {
      document.body.style.fontFamily = '';
    }

    if (lang === 'ar') {
      document.documentElement.setAttribute('dir', 'rtl');
    } else {
      document.documentElement.setAttribute('dir', 'ltr');
    }

    // 4. Translate the entire DOM instantly via TreeWalker
    translateEntireDOM(lang);

    // 5. Fire application-wide event so analysis cards, recommendations,
    // and stage guidance update seamlessly in sync
    window.dispatchEvent(new CustomEvent('mediscan:languageChanged', { detail: { lang } }));
  };

  // Expose dictionary for helper lookups
  window.MEDISCAN_TRANSLATIONS = TRANSLATIONS;

  // On page load, apply saved language
  document.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem('mediscan_language') || 'en';
    if (saved !== 'en') {
      setTimeout(() => {
        window.changeGlobalLanguage(saved);
      }, 50);
    }
  });

